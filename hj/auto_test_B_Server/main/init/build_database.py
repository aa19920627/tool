from component.loading_config import database_config
from component.sqlite_method import ManageSqlite

# 数据库名
DATABASE_NAME = database_config()


def build_database():
    # 初始化数据库连接类
    _ms = ManageSqlite(DATABASE_NAME)

    # 创建station表，存放监测站基本信息
    sql_station = '''CREATE TABLE IF NOT EXISTS station
                (id INTEGER PRIMARY KEY AUTOINCREMENT,
                mfid VARCHAR (14),
                mfname VARCHAR (50),
                area VARCHAR (6))
    '''
    # 创建device表，存放设备信息
    sql_device = '''CREATE TABLE IF NOT EXISTS device
                (id INTEGER PRIMARY KEY AUTOINCREMENT,
                mfid VARCHAR(14),
                mfname VARCHAR (50),
                equid VARCHAR (50),
                equname VARCHAR (50),
                type VARCHAR (1),
                ip VARCHAR (50),
                port VARCHAR (50)
                )
    '''
    # 创建function表，存放设备能力
    sql_function = '''CREATE TABLE IF NOT EXISTS function
                (id INTEGER PRIMARY KEY AUTOINCREMENT,
                mfid VARCHAR(14),
                mfname VARCHAR (50),
                equid VARCHAR (50),
                equname VARCHAR (50),
                fuc_name VARCHAR (50),
                fuc_en_name VARCHAR (50),
                url VARCHAR (255),
                request_message VARCHAR (10000)
                )
    '''
    # 创建function_base_info表，存放设备基础能力对照表
    sql_base_function = '''CREATE TABLE IF NOT EXISTS function_base_info
                    (id INTEGER PRIMARY KEY AUTOINCREMENT,
                    fuc_en_name VARCHAR (50), 
                    fuc_name VARCHAR (50)   
                    )
    '''
    # 创建area表，存放省份，城市和区域号
    sql_area = '''CREATE TABLE IF NOT EXISTS area  
            (id  INTEGER PRIMARY KEY AUTOINCREMENT,
            code varchar(20) ,
            province varchar(255) ,
            city varchar(255) ,
            province_code varchar(20) 
            ) 
    '''
    # 执行sql
    _ms.operation_sqlite(sql_station, sql_device, sql_function, sql_base_function, sql_area)
    # 关闭连接
    _ms.close_cur_conn()


